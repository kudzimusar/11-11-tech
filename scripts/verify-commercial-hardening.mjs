import fs from 'node:fs'

const read = (path) => fs.readFileSync(path, 'utf8')
const assert = (condition, message) => {
  if (!condition) {
    console.error(`commercial-hardening: ${message}`)
    process.exitCode = 1
  }
}

const leadOps = read('src/lib/leadOps.ts')
const edge = read('supabase/functions/lead-intake/index.ts')
const migration = read('supabase/migrations/20260913023000_lead_operations_hardening.sql')
const securityMigration = read('supabase/migrations/20260913031000_explicit_lead_security.sql')
const dataHardeningMigration = read('supabase/migrations/20260913060000_native_data_hardening.sql')
const retentionMigration = read('supabase/migrations/20260913063000_ingress_retention_schedule.sql')
const eventIntegrityMigration = read('supabase/migrations/20260913064000_conversion_event_ip_required.sql')
const pagesWorkflow = read('.github/workflows/pages.yml')
const shell = read('src/components/SiteShell.tsx')
const policies = read('src/pages/Policies.tsx')
const sourceFiles = fs.readdirSync('src', { recursive: true })
  .filter((entry) => typeof entry === 'string' && /\.(ts|tsx)$/.test(entry))
  .map((entry) => read(`src/${entry}`))
  .join('\n')

assert(leadOps.includes('requestTimeoutMs = 12_000'), 'browser lead requests must have a bounded timeout')
assert(leadOps.includes('getSubmissionId()'), 'browser lead submissions must carry an idempotency identifier')
assert(leadOps.includes("'11t_attribution_v1'"), 'first-touch attribution must survive SPA navigation')
assert(leadOps.includes('landingPath'), 'landing path must be preserved for conversion attribution')
assert(!leadOps.includes('leadId: string'), 'browser lead confirmation must not depend on an internal database UUID')
assert(edge.includes('allowedEventTypes'), 'analytics event names must be allow-listed')
assert(edge.includes('request_id: requestId'), 'edge lead writes must persist the idempotency identifier')
assert(edge.includes("eq('request_id', requestId)"), 'edge lead writes must detect duplicate retries')
assert(edge.includes('AbortController()'), 'notification delivery must have a bounded timeout')
assert(edge.includes("Deno.env.get('IP_HASH_SALT') || Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')") && edge.includes("name: 'HMAC'") && edge.includes('Ingress hash secret is not configured'), 'ingress hashing must use a private server-side HMAC secret and fail closed if no server secret exists')
assert(edge.includes('Origin not allowed'), 'edge function must reject unapproved browser origins')
assert(edge.includes('Content type must be application/json'), 'edge function must reject non-JSON POST bodies')
assert(edge.includes("consumeRateLimit('lead-ip'") && edge.includes("consumeRateLimit('lead-email'") && edge.includes("consumeRateLimit('event-ip'"), 'lead and event abuse controls must use the atomic database limiter')
assert(edge.includes('existing.email !== email'), 'idempotency identifiers must be bound to the same normalized email')
assert(!edge.includes('leadId:'), 'public lead responses must not expose internal lead UUIDs')
assert(edge.includes("url.search = ''") && edge.includes("url.hash = ''"), 'stored website URLs must discard query strings and fragments')
assert(migration.includes('leads_request_id_uidx'), 'database must enforce unique lead request identifiers')
assert(migration.includes('leads_goals_length_check'), 'database must enforce core lead content bounds')
assert(securityMigration.includes('deny_public_leads') && securityMigration.includes('deny_public_conversion_events'), 'database must carry explicit deny policies for public lead data')
assert(securityMigration.includes('revoke execute on function public.assign_lead_reference() from public, anon, authenticated'), 'lead-reference trigger must not be callable as a public RPC')
assert(securityMigration.includes('revoke execute on function public.rls_auto_enable() from public, anon, authenticated'), 'RLS event trigger must not be callable as a public RPC')
assert(dataHardeningMigration.includes('alter column request_id set not null') && dataHardeningMigration.includes('alter column reference set not null'), 'database must require idempotency and business references')
assert(dataHardeningMigration.includes('leads_email_integrity_check') && dataHardeningMigration.includes('leads_capability_allowlist_check'), 'database must independently enforce normalized core lead fields')
assert(dataHardeningMigration.includes('consume_ingress_rate_limit') && dataHardeningMigration.includes("interval '48 hours'"), 'rate limiting must be atomic and carry defensive stale-row purging')
assert(dataHardeningMigration.includes('force row level security'), 'lead, analytics and limiter tables must force RLS')
assert(retentionMigration.includes("cron.schedule") && retentionMigration.includes("interval '48 hours'"), 'pseudonymous limiter retention must be enforced by a scheduled cleanup')
assert(eventIntegrityMigration.includes('alter column ip_hash set not null'), 'conversion analytics must require a server-derived pseudonymous ingress identity')
assert(pagesWorkflow.includes('https://aopwqtlxxqdlfftpcvwv.supabase.co/functions/v1/lead-intake'), 'production Pages build must target the dedicated 11-11 Tech lead endpoint')
assert(shell.includes('footer-trust-strip-v23') && shell.includes('footer-cta-v23') && shell.includes('corporate-footer-v23'), 'approved three-part footer composition must remain present')
assert(!shell.match(/TOYOTA|World Vision|BBC|UNHCR|Oxford|Safaricom/i), 'unsupported client logos or names must not be introduced into the footer')
assert(policies.includes('safe email fallback') || policies.includes('email fallback'), 'privacy policy must disclose the lead fallback behavior')
assert(policies.includes('48 hours') && policies.includes('native app'), 'privacy policy must disclose native telemetry scope and short-lived limiter retention')
assert(!sourceFiles.includes('SUPABASE_SERVICE_ROLE_KEY'), 'service-role keys must never be referenced by browser source')
assert(!sourceFiles.includes('RESEND_API_KEY'), 'Resend secrets must never be referenced by browser source')

if (!process.exitCode) console.log('commercial-hardening: all invariants passed')
